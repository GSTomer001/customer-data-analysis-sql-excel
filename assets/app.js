/* Customer Data Analysis - SQL & Excel report.
   Data comes from assets/report_data.js which is generated by scripts/analysis.py. */
(function () {
  "use strict";

  var REPORT = window.REPORT_DATA;
  var R = REPORT.results;
  var COUNT = REPORT.counts;

  var PALETTE = ["#1f6feb", "#2ea043", "#d29922", "#a371f7", "#ec6a5e", "#39c5cf"];

  function money(v) {
    return "Rs " + Math.round(v).toLocaleString("en-IN");
  }
  function shortMoney(v) {
    var a = Math.abs(v);
    if (a >= 1e7) return "Rs " + (v / 1e7).toFixed(2) + " Cr";
    if (a >= 1e5) return "Rs " + (v / 1e5).toFixed(2) + " Lakh";
    if (a >= 1e3) return "Rs " + (v / 1e3).toFixed(1) + "k";
    return money(v);
  }
  function num(v) {
    return Number(v).toLocaleString("en-IN");
  }

  // ---------- KPI cards ----------
  function renderKpis() {
    var k = (R.kpi_overview && R.kpi_overview[0]) || {};
    var cards = [
      ["Customers", num(k.total_customers || 0), num(k.buying_customers || 0) + " have purchased"],
      ["Orders", num(k.total_orders || 0), "3 financial years"],
      ["Total revenue", shortMoney(k.total_revenue || 0), money(k.total_revenue || 0)],
      ["Units sold", num(k.units_sold || 0), "order lines"],
      ["Average order value", shortMoney(k.avg_order_value || 0), "revenue / order"],
      ["Analysis queries", num(REPORT.queries.length), "SQL statements executed"]
    ];
    document.getElementById("kpis").innerHTML = cards.map(function (card) {
      return '<div class="kpi"><span>' + card[0] + '</span><strong>' + card[1] +
        '</strong><small>' + card[2] + '</small></div>';
    }).join("");
  }

  // ---------- data model ----------
  var TABLES = [
    ["customers", "Dimension", "customer_id, first_name, last_name, email, phone, city, state, country, signup_date, segment, loyalty_tier"],
    ["products", "Dimension", "product_id, product_name, category, unit_price"],
    ["orders", "Fact (header)", "order_id, customer_id, order_date, order_year, order_month, channel, payment_method, status"],
    ["order_items", "Fact (line)", "order_item_id, order_id, product_id, quantity, unit_price, discount_pct, line_total"]
  ];

  function renderModel() {
    document.getElementById("modelNote").textContent =
      "Cleaned row counts after de-duplication, label standardisation and integrity checks: " +
      Object.keys(COUNT).map(function (name) { return name + " = " + num(COUNT[name]); }).join(" · ") + ".";
    document.getElementById("schemaTable").querySelector("tbody").innerHTML =
      TABLES.map(function (row) {
        return "<tr><td><code>" + row[0] + "</code></td><td>" + row[1] + "</td>" +
          "<td class='num'>" + num(COUNT[row[0]] || 0) + "</td><td>" + row[2] + "</td></tr>";
      }).join("");
  }

  // ---------- Excel + quality tables ----------
  var EXCEL_SHEETS = [
    ["Read_me", "Workbook contents and conventions"],
    ["Customers / Products / Orders / Order_Items", "Cleaned data extracted from the SQL model"],
    ["Orders_Enriched", "VLOOKUP (3 columns) + XLOOKUP (loyalty tier) look-ups against the Customers sheet"],
    ["Pivot_Segment", "Pivot-style summary with COUNTIF / COUNTIFS / SUMIF / AVERAGEIFS formulas"],
    ["Pivot_State", "Regional revenue with share-of-total formulas + conditional formatting scales"],
    ["Query_Results", "Output of the SQL analysis, ready for pivoting"]
  ];

  function renderExcel() {
    document.getElementById("excelTable").querySelector("tbody").innerHTML =
      EXCEL_SHEETS.map(function (row) {
        return "<tr><td><code>" + row[0] + "</code></td><td>" + row[1] + "</td></tr>";
      }).join("");
  }

  function renderQuality() {
    var q = REPORT.quality;
    var rows = [
      ["Raw rows read from the CRM extracts", Object.keys(q.raw_rows)
        .map(function (k) { return k + " " + num(q.raw_rows[k]); }).join(", ")],
      ["Clean rows loaded into the database", Object.keys(q.clean_rows)
        .map(function (k) { return k + " " + num(q.clean_rows[k]); }).join(", ")],
      ["Duplicate customer records removed", num(q.duplicate_customers_removed)],
      ["Inconsistent text labels standardised", num(q.labels_standardised)],
      ["Missing city values imputed", num(q.missing_values.city)],
      ["Missing email values imputed", num(q.missing_values.email)],
      ["Orphan order lines dropped (failed FK)", num(q.orphan_order_items_removed)]
    ];
    document.getElementById("qualityTable").querySelector("tbody").innerHTML =
      rows.map(function (row) {
        return "<tr><td>" + row[0] + "</td><td class='num'>" + row[1] + "</td></tr>";
      }).join("");
  }

  // ---------- charts ----------
  var charts = {};
  var moneyAxis = {
    ticks: { callback: function (value) { return shortMoney(value); } },
    grid: { color: "#eef2f7" }
  };

  function draw(id, config) {
    if (charts[id]) { charts[id].destroy(); }
    charts[id] = new Chart(document.getElementById(id), config);
  }

  function renderCharts() {
    // 1) revenue by segment (+ average order value on a second axis)
    var seg = R.revenue_by_segment || [];
    draw("segmentChart", {
      data: {
        labels: seg.map(function (r) { return r.segment; }),
        datasets: [
          {
            type: "bar", label: "Revenue", data: seg.map(function (r) { return r.revenue; }),
            backgroundColor: PALETTE[0], borderRadius: 5, yAxisID: "y"
          },
          {
            type: "line", label: "Avg order value", data: seg.map(function (r) { return r.avg_order_value; }),
            borderColor: PALETTE[4], backgroundColor: PALETTE[4], tension: 0.25, pointRadius: 4, yAxisID: "y1"
          }
        ]
      },
      options: {
        maintainAspectRatio: false,
        interaction: { mode: "index", intersect: false },
        plugins: {
          legend: { position: "bottom" },
          tooltip: {
            callbacks: {
              label: function (c) {
                return c.dataset.label === "Revenue"
                  ? "Revenue: " + money(c.parsed.y)
                  : "Avg order value: " + money(c.parsed.y);
              }
            }
          }
        },
        scales: {
          y: moneyAxis,
          y1: {
            position: "right", grid: { display: false },
            ticks: { callback: function (v) { return shortMoney(v); } }
          },
          x: { grid: { display: false } }
        }
      }
    });

    // 2) customer value tiers
    var tiers = R.customer_value_tiers || [];
    draw("tierChart", {
      type: "doughnut",
      data: {
        labels: tiers.map(function (r) { return r.value_tier; }),
        datasets: [{
          data: tiers.map(function (r) { return r.customers; }),
          backgroundColor: PALETTE, borderColor: "#fff", borderWidth: 2
        }]
      },
      options: {
        maintainAspectRatio: false, cutout: "55%",
        plugins: {
          legend: { position: "bottom" },
          tooltip: {
            callbacks: {
              label: function (c) {
                var row = tiers[c.dataIndex];
                return c.label + ": " + num(c.parsed) + " customers (" + money(row.total_revenue) + ")";
              }
            }
          }
        }
      }
    });

    // 3) revenue by state
    var states = (R.revenue_by_state || []).slice().sort(function (a, b) { return b.revenue - a.revenue; });
    draw("stateChart", {
      type: "bar",
      data: {
        labels: states.map(function (r) { return r.state; }),
        datasets: [{
          label: "Revenue", data: states.map(function (r) { return r.revenue; }),
          backgroundColor: PALETTE[2], borderRadius: 5
        }]
      },
      options: {
        maintainAspectRatio: false, indexAxis: "y",
        plugins: {
          legend: { display: false },
          tooltip: {
            callbacks: {
              label: function (c) {
                var row = states[c.dataIndex];
                return money(c.parsed.x) + " (" + row.revenue_share_pct + "% of total, " +
                  num(row.orders) + " orders)";
              }
            }
          }
        },
        scales: { x: moneyAxis, y: { grid: { display: false } } }
      }
    });

    // 4) category performance
    var cats = R.revenue_by_category || [];
    draw("categoryChart", {
      data: {
        labels: cats.map(function (r) { return r.category; }),
        datasets: [
          {
            type: "bar", label: "Revenue", data: cats.map(function (r) { return r.revenue; }),
            backgroundColor: PALETTE[1], borderRadius: 5, yAxisID: "y"
          },
          {
            type: "line", label: "Avg discount %", data: cats.map(function (r) { return r.avg_discount_pct; }),
            borderColor: PALETTE[4], backgroundColor: PALETTE[4], tension: 0.25, pointRadius: 4, yAxisID: "y1"
          }
        ]
      },
      options: {
        maintainAspectRatio: false,
        interaction: { mode: "index", intersect: false },
        plugins: {
          legend: { position: "bottom" },
          tooltip: {
            callbacks: {
              label: function (c) {
                return c.dataset.label === "Revenue"
                  ? "Revenue: " + money(c.parsed.y)
                  : "Avg discount: " + c.parsed.y.toFixed(2) + "%";
              }
            }
          }
        },
        scales: {
          y: moneyAxis,
          y1: {
            position: "right", grid: { display: false },
            ticks: { callback: function (v) { return v + "%"; } }
          },
          x: { grid: { display: false } }
        }
      }
    });

    // 5) monthly trend with running total
    var trend = R.monthly_revenue_trend || [];
    draw("trendChart", {
      type: "line",
      data: {
        labels: trend.map(function (r) { return r.month; }),
        datasets: [
          {
            label: "Monthly revenue", data: trend.map(function (r) { return r.revenue; }),
            borderColor: PALETTE[0], backgroundColor: "rgba(31,111,235,.14)",
            fill: true, tension: 0.3, pointRadius: 2
          },
          {
            label: "Running total", data: trend.map(function (r) { return r.running_total; }),
            borderColor: PALETTE[3], borderDash: [6, 4], tension: 0.2, pointRadius: 0, fill: false
          }
        ]
      },
      options: {
        maintainAspectRatio: false,
        interaction: { mode: "index", intersect: false },
        plugins: {
          legend: { position: "bottom" },
          tooltip: { callbacks: { label: function (c) { return c.dataset.label + ": " + money(c.parsed.y); } } }
        },
        scales: {
          y: moneyAxis,
          x: { grid: { display: false }, ticks: { maxRotation: 90, font: { size: 10 } } }
        }
      }
    });

    // 6) revenue by channel and year
    var ch = R.channel_year_crosstab || [];
    draw("channelYearChart", {
      type: "bar",
      data: {
        labels: ch.map(function (r) { return r.channel; }),
        datasets: [
          { label: "2023", data: ch.map(function (r) { return r.y2023; }), backgroundColor: PALETTE[0], borderRadius: 4 },
          { label: "2024", data: ch.map(function (r) { return r.y2024; }), backgroundColor: PALETTE[1], borderRadius: 4 },
          { label: "2025", data: ch.map(function (r) { return r.y2025; }), backgroundColor: PALETTE[2], borderRadius: 4 }
        ]
      },
      options: {
        maintainAspectRatio: false,
        plugins: {
          legend: { position: "bottom" },
          tooltip: { callbacks: { label: function (c) { return c.dataset.label + ": " + money(c.parsed.y); } } }
        },
        scales: { y: moneyAxis, x: { grid: { display: false } } }
      }
    });

    // 7) order status mix per channel (stacked)
    var st = R.status_by_channel || [];
    var statuses = [
      { key: "delivered", label: "Delivered", color: PALETTE[1] },
      { key: "shipped", label: "Shipped", color: PALETTE[0] },
      { key: "pending", label: "Pending", color: PALETTE[2] },
      { key: "cancelled", label: "Cancelled", color: PALETTE[4] },
      { key: "returned", label: "Returned", color: PALETTE[3] }
    ];
    draw("statusChart", {
      type: "bar",
      data: {
        labels: st.map(function (r) { return r.channel; }),
        datasets: statuses.map(function (s) {
          return {
            label: s.label, data: st.map(function (r) { return r[s.key]; }),
            backgroundColor: s.color, borderRadius: 3
          };
        })
      },
      options: {
        maintainAspectRatio: false,
        plugins: { legend: { position: "bottom" } },
        scales: {
          x: { stacked: true, grid: { display: false } },
          y: { stacked: true, grid: { color: "#eef2f7" } }
        }
      }
    });
  }

  // ---------- top customers table ----------
  function renderTopCustomers() {
    var rows = R.top_10_customers || [];
    if (!rows.length) { return; }
    var headers = Object.keys(rows[0]);
    var table = document.getElementById("topCustomers");
    table.querySelector("thead").innerHTML = "<tr>" + headers.map(function (h) {
      var isNum = typeof rows[0][h] === "number";
      return "<th class='" + (isNum ? "num" : "") + "'>" + h.replace(/_/g, " ") + "</th>";
    }).join("") + "</tr>";
    table.querySelector("tbody").innerHTML = rows.map(function (row) {
      return "<tr>" + headers.map(function (h) {
        var value = row[h];
        var isNum = typeof value === "number";
        return "<td class='" + (isNum ? "num" : "") + "'>" + (isNum ? num(value) : value) + "</td>";
      }).join("") + "</tr>";
    }).join("");
  }

  // ---------- SQL query explorer ----------
  function cellHtml(rows, header, value) {
    var isNum = typeof rows[0][header] === "number";
    return "<td class='" + (isNum ? "num" : "") + "'>" + (isNum ? num(value) : value) + "</td>";
  }

  function renderQueries() {
    var host = document.getElementById("queryList");
    host.innerHTML = REPORT.queries.map(function (query, index) {
      var rows = R[query.key] || [];
      var headers = rows.length ? Object.keys(rows[0]) : [];
      var tableHtml = headers.length
        ? "<div class='table-wrap'><table><thead><tr>" + headers.map(function (h) {
          return "<th class='" + (typeof rows[0][h] === "number" ? "num" : "") + "'>" +
            h.replace(/_/g, " ") + "</th>";
        }).join("") + "</tr></thead><tbody>" + rows.slice(0, 25).map(function (row) {
          return "<tr>" + headers.map(function (h) {
            return cellHtml(rows, h, row[h]);
          }).join("") + "</tr>";
        }).join("") + "</tbody></table></div>"
        : "<p class='muted'>No rows returned.</p>";

      var note = rows.length > 25 ? " (showing the first 25)" : "";
      return "<details" + (index === 0 ? " open" : "") + "><summary>" + query.title +
        "<span class='key'>" + query.key + "</span></summary>" +
        "<pre>" + query.sql.replace(/&/g, "&amp;").replace(/</g, "&lt;") + "</pre>" +
        "<p class='result-note'>Result: " + num(rows.length) + " row(s)" + note + "</p>" +
        tableHtml + "</details>";
    }).join("");
  }

  function init() {
    renderKpis();
    renderModel();
    renderExcel();
    renderQuality();
    renderCharts();
    renderTopCustomers();
    renderQueries();
  }

  init();
})();

